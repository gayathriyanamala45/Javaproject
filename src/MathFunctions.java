
public class MathFunctions {

	public static void main(String[] args) {
    int a=10;
    double b=9.9;
    
    System.out.println("Absoulte:"+Math.abs(b));
    
    System.out.println("Floor:"+Math.floor(a));
    
    System.out.println("Ceiling:"+Math.ceil(b));
    
    System.out.println("Round:"+Math.round(a));
    
    System.out.println("Square Root:"+Math.sqrt(b));
    
    System.out.println("Power:"+Math.pow(2,4));
    
    System.out.println("Maximum:"+Math.max(10,9.9));
    
    System.out.println("Manimum:"+Math.min(10,9.9));
    
    System.out.println("Random:"+Math.random());
    
    System.out.println("Maximum:"+Math.max(a,b));
    
    
	}

}
