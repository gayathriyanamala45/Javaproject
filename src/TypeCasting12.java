
public class TypeCasting12 {

	public static void main(String[] args) {
        //1.int to long
		int a=30;
		long b=a;
		System.out.println(b);
		//2.byte to short
		byte c=10;
		short d=c;
		System.out.println(d);
		//3.short to int
		short f=20;
		int g=f;
		System.out.println(g);
		//4.long to float
		long h=15;
		float i=h;
		System.out.println(i);
		//5.float to double
		float j=25.5f;
		double k=j;
		System.out.println(k);
		//6.int to double
		int l=35;
		double m=l;
		System.out.println(m);
		//7.double to int
		double n=33.7;
		int o=(int)n;
		System.out.println(o);
		//8.float to int
		float x=55.5f;
		int y=(int)x;
		System.out.println(y);
		//9.long to int
		long A=45;
		int B=(int)A;
		System.out.println(B);
		//10.int to byte
		int C=26;
		byte D=(byte)C;
		System.out.println(D);
		//11.double to float
		double E=23.43;
		float F=(float)E;
		System.out.println(F);
		//12.char to int
		char G='h';
		int H=G;
		System.out.println(H);
		
		
		
		
	}

}
